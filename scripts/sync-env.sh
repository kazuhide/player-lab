#!/usr/bin/env bash
# Materialize per-app credential files from the repo-root .env — the single
# source for every key (docs/SETUP.md). Web/Vite reads .env directly; the
# native toolchains each need their own format, all untracked:
#
#   apps/ios/Local.xcconfig        xcodegen configFiles → Info.plist build settings
#   apps/android/local.properties  gradle fallback (merged; sdk.dir is preserved)
#   apps/react-native/.env         EXPO_PUBLIC_* — copy into the Expo app with App.tsx
#
# Vega has no file to generate: its Kepler entry sets
# globalThis.BITMOVIN_PLAYER_LICENSE_KEY / BITMOVIN_ANALYTICS_LICENSE_KEY (README).
#
# The iOS/RN files are fully GENERATED — hand edits there are overwritten on
# every run (put web overrides in apps/web/.env, not here). local.properties is
# the one exception: it is merged, and sdk.dir/other lines survive.
#
# Values are never printed. Re-run whenever .env changes. ENV_FILE=... overrides
# the .env location (used by scripts/test-env-lib.sh).
set -euo pipefail
umask 077   # credential files: owner-only, consistently
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
# shellcheck source=env-lib.sh
. "$ROOT/scripts/env-lib.sh"

ENV_FILE="${ENV_FILE:-$ROOT/.env}"
if [ ! -f "$ENV_FILE" ]; then
  echo "sync-env: no $ENV_FILE — nothing to sync (copy .env.example to .env first)."
  exit 0
fi
load_env_defaults "$ENV_FILE"

PLAYER_KEY="${BITMOVIN_PLAYER_LICENSE_KEY:-}"
ANALYTICS_KEY="${BITMOVIN_ANALYTICS_LICENSE_KEY:-}"
state() { [ -n "$1" ] && echo "set" || echo "unset"; }

# ── iOS: xcodegen picks up Local.xcconfig (configFiles in project.yml) ──
cat > "$ROOT/apps/ios/Local.xcconfig" <<EOF
// Generated by scripts/sync-env.sh from the repo-root .env — untracked; hand edits are overwritten.
BITMOVIN_PLAYER_LICENSE_KEY = $PLAYER_KEY
BITMOVIN_ANALYTICS_LICENSE_KEY = $ANALYTICS_KEY
EOF
echo "ios:     apps/ios/Local.xcconfig written (player=$(state "$PLAYER_KEY"), analytics=$(state "$ANALYTICS_KEY")) — rerun xcodegen"

# ── Android: merge into local.properties (its existence flips the :app module
#    on, so only write when an SDK context already exists — see settings.gradle.kts).
LP="$ROOT/apps/android/local.properties"
SDK_DIR="${ANDROID_HOME:-${ANDROID_SDK_ROOT:-$HOME/Library/Android/sdk}}"
if [ -f "$LP" ] || [ -d "$SDK_DIR" ]; then
  TMP="$(mktemp)"
  trap 'rm -f "$TMP"' EXIT
  [ -f "$LP" ] && grep -v '^bitmovinLicenseKey=\|^bitmovinAnalyticsLicenseKey=' "$LP" > "$TMP" || true
  if ! grep -q '^sdk.dir=' "$TMP" 2>/dev/null && [ -d "$SDK_DIR" ]; then
    echo "sdk.dir=$SDK_DIR" >> "$TMP"
  fi
  {
    echo "bitmovinLicenseKey=$PLAYER_KEY"
    echo "bitmovinAnalyticsLicenseKey=$ANALYTICS_KEY"
  } >> "$TMP"
  mv "$TMP" "$LP"
  echo "android: apps/android/local.properties merged (player=$(state "$PLAYER_KEY"), analytics=$(state "$ANALYTICS_KEY"))"
else
  echo "android: skipped — no Android SDK found (creating local.properties would switch the :app module on)"
fi

# ── React Native (Expo): EXPO_PUBLIC_* vars; ship this file with App.tsx/src ──
cat > "$ROOT/apps/react-native/.env" <<EOF
# Generated by scripts/sync-env.sh — hand edits are overwritten on every run.
# Copy into the Expo app together with App.tsx and src/ (see apps/react-native/README.md).
EXPO_PUBLIC_BITMOVIN_PLAYER_LICENSE_KEY=$PLAYER_KEY
EXPO_PUBLIC_BITMOVIN_ANALYTICS_LICENSE_KEY=$ANALYTICS_KEY
EOF
echo "rn:      apps/react-native/.env written (player=$(state "$PLAYER_KEY"), analytics=$(state "$ANALYTICS_KEY"))"
